import type { Oracle, TestIdentity } from './quality.js';
import type { FindingReplay } from './reproduction.js';

/**
 * Evidence rules of a v4 run, copied into the run when it is created. Reading, resuming or changing environment variables
 * later never loosens them: every field here is a fixed decision, kept in the record so a report can state what applied.
 */
export interface EvidencePolicy {
  schemaVersion: 1;
  /** A test correction is only ever applied after a person read its diff. */
  autoTestRepair: false;
  /** A manifest guessed from test titles is never evidence that a step has an assertion. */
  derivedManifest: false;
  /** A plan the Author did not write is a draft to fix, never a valid plan. */
  completePlan: false;
  /** Quotations and diagnosis labels are never rewritten to pass validation. */
  groundDiagnosis: false;
  /** An unproven blocker/major finding keeps blocking even after one repair round. */
  strictFindings: true;
  /** A confirmed behavioural finding leaves a locked regression test in the project. */
  regression: true;
  replay: { maxProbes: 3; probeMs: 30_000; batchMs: 60_000 };
}
export const EVIDENCE_POLICY_V4: EvidencePolicy = {
  schemaVersion: 1, autoTestRepair: false, derivedManifest: false, completePlan: false, groundDiagnosis: false, strictFindings: true, regression: true,
  replay: { maxProbes: 3, probeMs: 30_000, batchMs: 60_000 },
};

export const DEFAULT_REGRESSION_DIR = 'tests/aidept-regressions';

/** What the generated test did when it was tried once on a clone of the checkpoint, before anyone confirmed anything. */
export interface RegressionTrial {
  /** `breaks_checks`: the test failed where it should, but adding it makes another required check that passed on the checkpoint fail (a typecheck, say). */
  status: 'failed_as_expected' | 'passed_unexpectedly' | 'wrong_failure' | 'discovery_error' | 'breaks_checks' | 'error' | 'timeout' | 'interrupted';
  checkpoint: string; message: string; durationMs: number;
  /** Id of the test as the runner reports it, when the runner found it. */
  testId?: string;
  /** First line of the failure message, which must name the step the replay saw differ. */
  failure?: string;
}

/**
 * The regression test that would be added if a person confirms the finding. Generated by code from the finding's
 * scenario, never by a model, and shown with the diff before anything is applied.
 */
export interface RegressionProposal {
  schemaVersion: 1;
  findingId: string; scenarioHash: string; checkpoint: string; contractVersion: number; contractHash: string; configHash: string;
  slot: 'A' | 'B';
  /** Set when no regression can be generated here; the finding then needs a manual review with this limit stated. */
  unsupported?: string;
  recipeId?: string; path?: string; patch?: string; testHash?: string; testId?: string; identity?: TestIdentity; title?: string;
  oracle: Oracle;
  /** The runner's replay that this regression restates, with the step that differed. */
  replay: Pick<FindingReplay, 'status' | 'checkpoint' | 'message' | 'observations'>;
  trial?: RegressionTrial;
}
export interface PendingRegression extends RegressionProposal { id: string; hash: string }

/** A person read the oracle and the diff of one proposal; any change to what it names makes the receipt worthless. */
export interface RegressionReceipt {
  schemaVersion: 1; findingId: string; proposalId: string; proposalHash: string; scenarioHash: string; checkpoint: string;
  contractVersion: number; contractHash: string; configHash: string; slot: 'A' | 'B'; testHash: string; path: string; testId: string; confirmedAt: string;
}

/** What a repair applied before the Developer ran: the locked tests, with their file hashes and the proposals behind them. */
export interface RegressionManifest {
  schemaVersion: 1; contractVersion: number; contractHash: string; slot: 'A' | 'B'; checkpoint: string; createdAt: string;
  entries: {
    findingId: string; scenarioHash: string; recipeId: string; path: string; testId: string; identity: TestIdentity; fileHash: string; proposalHash: string; receiptHash: string;
    /** The checkpoint the person confirmed on, and the commit that added exactly this test: a resume between the two is the same transaction. */
    appliedFrom?: string; appliedCheckpoint?: string;
  }[];
}

/** A regression file found in the project (shipped by an earlier run), identified by the header the generator writes. */
export interface RegressionRef {
  path: string; recipeId: string; testId: string; identity: TestIdentity; findingId: string; scenarioHash: string;
  /** False when the file no longer matches the hash in its own header: it was edited by hand or by an agent. */
  intact: boolean;
}

export interface FindingConfirmation {
  kind: 'regression' | 'manual'; at: string;
  proposalHash?: string; receiptHash?: string; reason?: string;
}
export interface FindingResolution {
  kind: 'verified_fix' | 'manual_review'; at: string;
  /** Required for manual_review. */
  reason?: string; checkpoint?: string;
  before?: { replay: FindingReplay['status']; checkpoint: string; regression?: RegressionTrial['status'] };
  after?: { replay: FindingReplay['status']; checkpoint: string; regression?: 'passed' | 'failed' | 'missing' };
  regressionTestId?: string;
  /** created: a locked test proves it; unsupported: the stack/runner cannot host one, so only the replay proves it. */
  regression?: 'created' | 'unsupported';
}

/** One finding on the ladder the report shows; only `proven_fixed` is a repair the runner demonstrated. */
export interface FindingProof {
  findingId: string; title: string; severity: 'blocker' | 'major' | 'minor';
  level: 'proven_fixed' | 'reproduced' | 'not_reproduced' | 'unverified' | 'manual_decision';
  replayBefore?: FindingReplay['status']; replayAfter?: FindingReplay['status'];
  regression?: 'created' | 'unsupported' | 'none'; regressionPath?: string; regressionTestId?: string;
  regressionBefore?: RegressionTrial['status']; regressionAfter?: 'passed' | 'failed' | 'missing';
  note: string;
}
